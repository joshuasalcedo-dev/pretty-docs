package io.joshuasalcedo.pretty.plugin;

import com.google.gson.Gson;
import com.google.gson.JsonParser;
import io.joshuasalcedo.pretty.JavaParser;
import io.joshuasalcedo.pretty.plugin.model.DocumentationSite;

import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.URISyntaxException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Writes the site: the prebuilt template (src/main/resources/pretty-site, built from ../pretty-site) plus the data files.
 */
public final class SiteWriter {

    /** Classpath folder holding the prebuilt site template. */
    static final String TEMPLATE_ROOT = "pretty-site";
    /** Marks a directory as ours, so regenerating may clear it. */
    static final String MARKER = ".pretty-docs";

    private final ClassLoader classLoader;

    public SiteWriter() {
        this(SiteWriter.class.getClassLoader());
    }

    SiteWriter(ClassLoader classLoader) {
        this.classLoader = classLoader;
    }

    /**
     * @return The site's {@code index.html}
     * @throws IOException if writing fails, or the directory is non-empty and was not created by us
     */
    public Path write(DocumentationSite site, Path outputDirectory) throws IOException {
        return write(site, outputDirectory, List.of());
    }

    /** Also writes each diagram's .puml (and .svg when rendered) under {@code diagrams/}. */
    public Path write(DocumentationSite site, Path outputDirectory, List<DiagramGenerator.Diagram> diagrams) throws IOException {
        prepare(outputDirectory);
        if (site.getReadmeAssets() != null) {
            Path root = outputDirectory.toAbsolutePath().normalize();
            for (Map.Entry<String, Path> asset : site.getReadmeAssets().entrySet()) {
                Path target = root.resolve(asset.getKey()).normalize();
                if (target.startsWith(root)) {
                    Files.createDirectories(target.getParent());
                    Files.copy(asset.getValue(), target, StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
        if (!diagrams.isEmpty()) {
            Files.createDirectories(outputDirectory.resolve("diagrams"));
        }
        for (DiagramGenerator.Diagram diagram : diagrams) {
            Files.writeString(outputDirectory.resolve(diagram.structure().getPumlPath()), diagram.puml(), StandardCharsets.UTF_8);
            if (diagram.svg() != null) {
                Files.write(outputDirectory.resolve(diagram.structure().getSvgPath()), diagram.svg());
            }
        }
        boolean template = copyTemplate(outputDirectory);
        if (!template) {
            try (InputStream in = SiteWriter.class.getResourceAsStream("fallback-index.html")) {
                Files.copy(in, outputDirectory.resolve("index.html"));
            }
        }
        String json = JavaParser.toJson(site, false);
        Files.writeString(outputDirectory.resolve("docs.json"), JavaParser.toJson(site, true), StandardCharsets.UTF_8);
        // The page loads an outline up front and each module's sources when one of its pages opens.
        Gson gson = new Gson();
        ModuleDataSplitter.Result split = ModuleDataSplitter.split(JsonParser.parseString(json).getAsJsonObject(), gson);
        Files.createDirectories(outputDirectory.resolve(ModuleDataSplitter.DIRECTORY));
        for (Map.Entry<String, String> script : split.moduleScripts().entrySet()) {
            Files.writeString(outputDirectory.resolve(script.getKey()), script.getValue(), StandardCharsets.UTF_8);
        }
        Files.writeString(outputDirectory.resolve("docs-data.js"),
                "window.__PRETTY_DOCS__ = " + gson.toJson(split.outline()) + ";\n", StandardCharsets.UTF_8);
        return outputDirectory.resolve("index.html");
    }

    /** True when the built template is on the classpath. */
    public boolean hasTemplate() {
        return classLoader.getResource(TEMPLATE_ROOT + "/index.html") != null;
    }

    private static void prepare(Path outputDirectory) throws IOException {
        if (Files.isDirectory(outputDirectory)) {
            boolean empty;
            try (Stream<Path> entries = Files.list(outputDirectory)) {
                empty = entries.findAny().isEmpty();
            }
            if (!empty && !Files.exists(outputDirectory.resolve(MARKER))) {
                throw new IOException("Refusing to overwrite " + outputDirectory
                        + ": it is not empty and was not generated by pretty-docs");
            }
            try (Stream<Path> walk = Files.walk(outputDirectory)) {
                for (Path path : walk.sorted(Comparator.reverseOrder()).toList()) {
                    if (!path.equals(outputDirectory)) {
                        Files.delete(path);
                    }
                }
            }
        }
        Files.createDirectories(outputDirectory);
        Files.writeString(outputDirectory.resolve(MARKER), "Generated by pretty-docs-maven-plugin; this directory is replaced on each run.\n");
    }

    private boolean copyTemplate(Path outputDirectory) throws IOException {
        URL index = classLoader.getResource(TEMPLATE_ROOT + "/index.html");
        if (index == null) {
            return false;
        }
        URI uri;
        try {
            uri = index.toURI();
        } catch (URISyntaxException e) {
            throw new IOException("Unreadable template location " + index, e);
        }
        if ("jar".equals(uri.getScheme())) {
            FileSystem fs;
            boolean opened = false;
            try {
                fs = FileSystems.newFileSystem(uri, Map.of());
                opened = true;
            } catch (FileSystemAlreadyExistsException e) {
                fs = FileSystems.getFileSystem(uri);
            }
            try {
                copyTree(fs.getPath("/" + TEMPLATE_ROOT), outputDirectory);
            } finally {
                if (opened) {
                    fs.close();
                }
            }
        } else {
            copyTree(Path.of(uri).getParent(), outputDirectory);
        }
        return true;
    }

    private static void copyTree(Path source, Path target) throws IOException {
        List<Path> paths;
        try (Stream<Path> walk = Files.walk(source)) {
            paths = walk.filter(Files::isRegularFile).toList();
        }
        for (Path path : paths) {
            Path destination = target.resolve(source.relativize(path).toString());
            Files.createDirectories(destination.getParent());
            try (InputStream in = Files.newInputStream(path)) {
                Files.copy(in, destination, StandardCopyOption.REPLACE_EXISTING);
            }
        }
    }

}
